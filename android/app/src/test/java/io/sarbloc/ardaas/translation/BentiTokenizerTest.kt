package io.sarbloc.ardaas.translation

import java.io.File
import java.security.MessageDigest
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Port of ArdaasTests/BentiTokenizerTests.swift, case for case: the Kotlin
 * preprocessing + tokenizer must reproduce the Python reference pipeline
 * id-for-id.
 *
 * `tokenizer_parity.json` was generated by running IndicTransToolkit 1.1.1 +
 * the reference tokenizer over 21 English sentences (see the fixture `_meta`
 * and docs/translation/README.md). Both fixtures are read from the iOS test
 * tree — passed in by Gradle — so there is one copy and nothing to keep in
 * sync. Never edit an expected value to make one side pass.
 */
class BentiTokenizerTest {

    @Serializable
    private data class Fixture(val cases: List<Case>) {
        @Serializable
        data class Case(
            val input: String,
            val preprocessed: String,
            @SerialName("token_ids") val tokenIds: List<Long>,
        )
    }

    private companion object {
        const val EXPECTED_TOKENIZER_SHA256 =
            "913a7fe797e866de46c805d237846ff6433387e77117c377fddeb28b221808da"

        /** Unknown keys (the fixture's `_meta`) are skipped, as Swift's Decodable does. */
        val fixtureJson = Json { ignoreUnknownKeys = true }

        fun sharedFixture(property: String): File = File(
            requireNotNull(System.getProperty(property)) { "$property not set — run through Gradle" },
        )

        val fixture: Fixture by lazy {
            fixtureJson.decodeFromString<Fixture>(
                sharedFixture("ardaas.tokenizerParityFixture").readText(Charsets.UTF_8),
            )
        }

        /** Immutable once loaded, so the 3.4 MB parse is paid once for the class. */
        val tokenizer: BentiTokenizer by lazy {
            BentiTokenizer(sharedFixture("ardaas.tokenizerSourceFixture"))
        }
    }

    /**
     * The shared tokenizer file must be byte-identical to the spec's
     * downloadable artifact — otherwise parity here proves nothing about what
     * runs on device.
     */
    @Test
    fun sharedTokenizerFileMatchesSpecHash() {
        val bytes = sharedFixture("ardaas.tokenizerSourceFixture").readBytes()
        val digest = MessageDigest.getInstance("SHA-256").digest(bytes)
            .joinToString("") { "%02x".format(it) }
        assertEquals(EXPECTED_TOKENIZER_SHA256, digest)
    }

    @Test
    fun fixtureCoverage() {
        assertTrue("only ${fixture.cases.size} cases", fixture.cases.size >= 12)
    }

    /** Moses-subset preprocessing parity: raw English → tagged token string. */
    @Test
    fun preprocessingParity() {
        for (case in fixture.cases) {
            assertEquals(
                "preprocess mismatch for input: ${case.input}",
                case.preprocessed,
                BentiPreprocessor.preprocess(case.input).tagged,
            )
        }
    }

    /** End-to-end encode parity: raw English → encoder-ready ids. */
    @Test
    fun tokenIdParity() {
        for (case in fixture.cases) {
            val tagged = BentiPreprocessor.preprocess(case.input).tagged
            assertArrayEquals(
                "token-id mismatch for input: ${case.input}",
                case.tokenIds.toLongArray(),
                tokenizer.encode(tagged),
            )
        }
    }

    /**
     * Tokenizer parity in isolation (fixture `preprocessed` → ids), so a
     * preprocessing bug can't mask a tokenizer bug or vice versa.
     */
    @Test
    fun tokenIdParityFromPreprocessedText() {
        for (case in fixture.cases) {
            assertArrayEquals(
                "token-id mismatch for preprocessed: ${case.preprocessed}",
                case.tokenIds.toLongArray(),
                tokenizer.encode(case.preprocessed),
            )
        }
    }

    /**
     * The extended-vocab remap (spec section 3.6): "Gmina" BPE-resolves to
     * fast-tokenizer id 32519 >= src_dict_size and must come out as <unk>=3.
     */
    @Test
    fun extendedVocabRemap() {
        assertArrayEquals(longArrayOf(4, 46, 3, 2), tokenizer.encode("eng_Latn pan_Guru Gmina"))
    }

    @Test
    fun languageTagsAndEos() {
        val ids = tokenizer.encode("eng_Latn pan_Guru Please")
        assertEquals(4L, ids.first()) // eng_Latn
        assertEquals(46L, ids[1]) // pan_Guru
        assertEquals(2L, ids.last()) // </s>
        assertTrue(ids.all { it < BentiTokenizer.SRC_DICT_SIZE })
    }

    /**
     * One benti is one model call — there is no sentence splitting — so past
     * the encoder's 256 positions the only honest answer is a refusal, not a
     * silent truncation into a mistranslation.
     */
    @Test
    fun overlongInputIsRefusedRatherThanTruncated() {
        BentiTokenizer.validateSourceLength(LongArray(BentiTokenizer.MAX_SOURCE_TOKENS) { 5 })

        val tooMany = LongArray(BentiTokenizer.MAX_SOURCE_TOKENS + 1) { 5 }
        val error = assertThrows(TranslationError.InputTooLong::class.java) {
            BentiTokenizer.validateSourceLength(tooMany)
        }
        assertEquals(TranslationError.InputTooLong(tooMany.size, BentiTokenizer.MAX_SOURCE_TOKENS), error)
    }

    /** A long benti really does exceed the cap, so the guard is reachable rather than theoretical. */
    @Test
    fun aLongBentiExceedsTheSourceLimit() {
        val sentence = "Please bless my family with health and happiness and peace. ".repeat(40)
        val ids = tokenizer.encode(BentiPreprocessor.preprocess(sentence).tagged)
        assertTrue("only ${ids.size} ids", ids.size > BentiTokenizer.MAX_SOURCE_TOKENS)
        assertThrows(TranslationError.InputTooLong::class.java) {
            BentiTokenizer.validateSourceLength(ids)
        }
    }

    /** A truncated or foreign file fails as a typed error naming the file, never a crash. */
    @Test
    fun malformedTokenizerFileIsATypedError() {
        val file = File.createTempFile("tokenizer_src", ".json")
        try {
            file.writeText("""{"added_tokens": [], "model": {"vocab": {}}}""")
            val error = assertThrows(TranslationError.MalformedModelFile::class.java) { BentiTokenizer(file) }
            assertEquals(file.name, error.name)
        } finally {
            file.delete()
        }
    }
}
