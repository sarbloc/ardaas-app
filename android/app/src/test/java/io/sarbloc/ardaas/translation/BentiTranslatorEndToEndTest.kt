/**
 * The whole pipeline on the real model, on the host: optimize the three
 * pinned graphs with [OnnxGraphOptimizer], then translate the 21 parity
 * sentences with [BentiTranslator] and require the reference pipeline's
 * output exactly — the generated ids and the final Gurmukhi.
 *
 * Opt-in, because the model is 359 MB and CI does not download it: set
 * `ARDAAS_MODEL_DIR` to a directory holding the catalog's files (the three
 * `.onnx` graphs, `tokenizer_src.json`, `tokenizer_meta.json`,
 * `dict.TGT.json`). Every file is SHA-256 checked against [ModelCatalog] first,
 * so a pass is a statement about exactly the artifacts the app downloads.
 *
 * Goldens: test resource `translation/translation_golden.json`, generated by
 * the Python reference pipeline over the *original* graphs (see its `_meta`).
 * Android-only on purpose: anything under `ArdaasTests/` triggers macOS CI.
 * Matching them here is also the parity check for the graph rewrite.
 */
class BentiTranslatorEndToEndTest {

    @Serializable
    private data class Golden(val cases: List<Case>) {
        @Serializable
        data class Case(
            val input: String,
            @SerialName("generated_ids") val generatedIds: List<Long>,
            val gurmukhi: String,
        )
    }

    companion object {
        private val catalog = ModelCatalog.PRODUCTION
        private const val GOLDEN_RESOURCE = "/translation/translation_golden.json"
        private val lenientJson = Json { ignoreUnknownKeys = true } // the golden's `_meta` header
        private lateinit var workDirectory: File
        private lateinit var translator: BentiTranslator
        private lateinit var golden: Golden

        @JvmStatic
        @BeforeClass
        fun optimizeTheRealGraphs() {
            val path = System.getProperty("ardaas.modelDir").orEmpty()
            assumeTrue("ARDAAS_MODEL_DIR is not set; skipping the real-model test", path.isNotEmpty())
            val modelDirectory = File(path)
            verifyAgainstCatalog(modelDirectory)

            val goldenText = requireNotNull(BentiTranslatorEndToEndTest::class.java.getResource(GOLDEN_RESOURCE)) {
                "$GOLDEN_RESOURCE is missing from the test classpath"
            }.readText(Charsets.UTF_8)
            golden = lenientJson.decodeFromString(goldenText)

            workDirectory = Files.createTempDirectory("benti-e2e").toFile()
            val optimized = File(workDirectory, "Optimized").apply { mkdirs() }
            val started = System.nanoTime()
            for (name in catalog.graphNames) {
                OnnxGraphOptimizer.optimize(
                    File(modelDirectory, name),
                    File(optimized, name),
                    ModelOptimizer.externalDataName(name),
                )
                OnnxGraphOptimizer.verifyLoadable(File(optimized, name))
            }
            val optimizedBytes = optimized.listFiles().orEmpty().sumOf { it.length() }
            println("optimize+verify: ${(System.nanoTime() - started) / 1_000_000} ms, cache ${optimizedBytes / 1_000_000} MB")

            translator = BentiTranslator(catalog, optimized, modelDirectory)
        }

        @JvmStatic
        @AfterClass
        fun deleteTheCache() {
            if (::workDirectory.isInitialized) workDirectory.deleteRecursively()
        }

        private fun verifyAgainstCatalog(directory: File) {
            for (artifact in catalog.artifacts) {
                val file = File(directory, artifact.name)
                assertTrue("${file.path} is missing", file.isFile)
                assertEquals("${artifact.name} is not the pinned artifact", artifact.sha256, ModelInstaller.sha256(file))
            }
        }
    }

    @Test
    fun reproducesTheReferencePipelineOnEveryGolden() = runBlocking {
        assertEquals(21, golden.cases.size)
        val memory = HostMemory.startPeakWindow()
        val mismatches = mutableListOf<String>()
        println("  #  tokens  latency  sessions  sentence")
        golden.cases.forEachIndexed { index, case ->
            val result = translator.translate(case.input)
            println(
                "%3d  %6d  %5d ms  %5d ms  %s".format(
                    index + 1, result.generatedIds.size, result.latencyMillis, result.sessionLoadMillis, case.input.take(48),
                ),
            )
            if (result.generatedIds != case.generatedIds) {
                mismatches += "#${index + 1} ids: expected ${case.generatedIds}, got ${result.generatedIds}"
            }
            if (result.gurmukhi != case.gurmukhi) {
                mismatches += "#${index + 1} text: expected «${case.gurmukhi}», got «${result.gurmukhi}»"
            }
        }
        println(memory.finish())
        if (mismatches.isNotEmpty()) fail("${mismatches.size} mismatches:\n" + mismatches.joinToString("\n"))
    }

    /**
     * The Android side of #52 on the real engine: cancelling mid-decode ends
     * in a CancellationException promptly — within a step, not after the rest
     * of a 122-token decode — and leaves the engine usable.
     */
    @Test
    fun cancellationMidDecodeStopsPromptlyAndLeavesTheEngineUsable() = runBlocking {
        val engine = TranslationEngine(memoryProbe = { null }, makeTranslator = { _, _, _ -> translator })
        val long = golden.cases.maxBy { it.generatedIds.size }
        val vocabulary = File(System.getProperty("ardaas.modelDir").orEmpty())

        val pending = async(Dispatchers.Default) { engine.translate(long.input, catalog, File("unused"), vocabulary) }
        // Past session loads and the encoder, well inside the decode loop.
        delay(1_000)
        val cancelledAt = System.nanoTime()
        pending.cancel()
        try {
            pending.await()
            fail("a cancelled translation must not produce a result")
        } catch (e: CancellationException) {
            val stopMillis = (System.nanoTime() - cancelledAt) / 1_000_000
            println("cancellation honoured after $stopMillis ms")
            assertTrue("took $stopMillis ms to stop", stopMillis < 1_000)
        }
        pending.join()

        val short = golden.cases.minBy { it.generatedIds.size }
        assertEquals(short.gurmukhi, engine.translate(short.input, catalog, File("unused"), vocabulary).gurmukhi)
    }
}

/**
 * Linux process memory from /proc/self, for host numbers comparable with
 * docs/translation/MEMORY.md ("peak anonymous memory").
 *
 * The host JVM lets its heap grow toward -Xmx before collecting the per-step
 * KV copies, so the committed heap is reported alongside the peak: the
 * growth figure is ORT's share only when the heap is small. With -Xmx128m the
 * same run passes at the same speed, which shows the live Java set is small.
 */
private class HostMemory private constructor(private val baseline: Map<String, Long>) {
    @Volatile private var running = true
    @Volatile private var peakAnonKb = 0L
    @Volatile private var peakHeapKb = 0L

    private val sampler = Thread {
        while (running) {
            peakAnonKb = maxOf(peakAnonKb, status()["RssAnon"] ?: 0)
            peakHeapKb = maxOf(peakHeapKb, Runtime.getRuntime().totalMemory() / 1024)
            Thread.sleep(SAMPLE_MILLIS)
        }
    }.apply {
        isDaemon = true
        start()
    }

    fun finish(): String {
        running = false
        sampler.join()
        val now = status()
        fun mb(kb: Long?) = "${(kb ?: 0) / 1024} MB"
        val growthKb = peakAnonKb - (baseline["RssAnon"] ?: 0)
        return "host memory: VmRSS before ${mb(baseline["VmRSS"])}, RssAnon before ${mb(baseline["RssAnon"])}; " +
            "peak RssAnon growth over the translations ${mb(growthKb)}; " +
            "peak VmHWM ${mb(now["VmHWM"])}, peak RssAnon (sampled every $SAMPLE_MILLIS ms) ${mb(peakAnonKb)}, " +
            "of which up to ${mb(peakHeapKb)} is committed JVM heap; " +
            "VmRSS after ${mb(now["VmRSS"])}"
    }

    companion object {
        private const val SAMPLE_MILLIS = 5L

        /** Resets the kernel's peak-RSS mark (clear_refs 5) so VmHWM covers only what follows. */
        fun startPeakWindow(): HostMemory {
            File("/proc/self/clear_refs").writeText("5")
            return HostMemory(status())
        }

        private fun status(): Map<String, Long> = File("/proc/self/status").readLines()
            .mapNotNull { line ->
                val parts = line.split(Regex("\\s+"))
                if (parts.size >= 2 && parts[0].endsWith(":")) parts[1].toLongOrNull()?.let { parts[0].dropLast(1) to it } else null
            }
            .toMap()
    }
}
